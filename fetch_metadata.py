#!/usr/bin/env python3
"""Fetch HuggingFace model metadata and README."""

import json
import requests
from pathlib import Path

def main():
    output_dir = Path(__file__).parent
    
    # Fetch model info from HuggingFace API
    print("Fetching model metadata from HuggingFace API...")
    response = requests.get("https://huggingface.co/api/models/haqaeb/amira-lora-sdxl")
    response.raise_for_status()
    metadata = response.json()
    
    # Save raw JSON
    metadata_path = output_dir / "metadata.json"
    with open(metadata_path, "w") as f:
        json.dump(metadata, f, indent=2)
    print(f"Saved metadata to {metadata_path}")
    
    # Try to fetch README
    readme_path = output_dir / "readme.md"
    readme_url = "https://huggingface.co/haqaeb/amira-lora-sdxl/raw/main/README.md"
    
    try:
        readme_response = requests.get(readme_url, timeout=10)
        if readme_response.status_code == 200:
            readme_path.write_text(readme_response.text)
            print(f"Saved README to {readme_path}")
        else:
            readme_path.write_text(f"README not found (HTTP {readme_response.status_code})")
            print(f"README fetch failed with status {readme_response.status_code}")
    except Exception as e:
        readme_path.write_text(f"Error fetching README: {e}")
        print(f"Error fetching README: {e}")
    
    # Create summary markdown
    summary_path = output_dir / "metadata_summary.md"
    summary_lines = [
        "# Model Metadata Summary: haqaeb/amira-lora-sdxl",
        "",
        "## Basic Information",
        f"- **Model ID:** {metadata.get('id', 'N/A')}",
        f"- **Author:** {metadata.get('author', 'N/A')}",
        f"- **Private:** {metadata.get('private', 'N/A')}",
        "",
        "## Statistics",
        f"- **Downloads:** {metadata.get('downloads', 0)}",
        f"- **Likes:** {metadata.get('likes', 0)}",
        "",
        "## Timestamps",
        f"- **Created:** {metadata.get('createdAt', 'N/A')}",
        f"- **Last Modified:** {metadata.get('lastModified', 'N/A')}",
        "",
        "## Tags",
        f"- **Tags:** {metadata.get('tags', [])}",
        "",
        "## SHA / Version",
        f"- **Commit SHA:** {metadata.get('sha', 'N/A')}",
        "",
        "## Files in Repository",
    ]
    
    siblings = metadata.get('siblings', [])
    for sibling in siblings:
        filename = sibling.get('rfilename', 'unknown')
        summary_lines.append(f"- `{filename}`")
    
    summary_lines.extend([
        "",
        "## Storage",
        f"- **Used Storage:** {metadata.get('usedStorage', 0)} bytes",
        "",
        "## Raw JSON",
        "",
        "See `metadata.json` for the complete raw API response.",
        "",
        "---",
        "*Generated by fetch_metadata.py*",
    ])
    
    summary_path.write_text("\n".join(summary_lines))
    print(f"Saved summary to {summary_path}")
    
    print("\nDone!")

if __name__ == "__main__":
    main()
