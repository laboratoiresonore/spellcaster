def _txt2img_workflow(ckpt: str, prompt: str, negative: str,
                      width: int, height: int, *,
                      steps: int = 28, cfg: float = 6.5,
                      sampler: str = "dpmpp_2m_sde",
                      scheduler: str = "karras",
                      seed: int | None = None) -> dict:
    """SDXL txt2img workflow — mirrors generate_showcase.txt2img()."""
    s = seed if seed is not None else int.from_bytes(os.urandom(4), "big")
    return {
        "1": {"class_type": "CheckpointLoaderSimple",
              "inputs": {"ckpt_name": ckpt}},
        "2": {"class_type": "CLIPTextEncode",
              "inputs": {"text": prompt, "clip": ["1", 1]}},
        "3": {"class_type": "CLIPTextEncode",
              "inputs": {"text": negative, "clip": ["1", 1]}},
        "4": {"class_type": "EmptyLatentImage",
              "inputs": {"width": width, "height": height, "batch_size": 1}},
        "5": {"class_type": "KSampler",
              "inputs": {"model": ["1", 0], "positive": ["2", 0],
                         "negative": ["3", 0], "latent_image": ["4", 0],
                         "seed": s, "steps": steps, "cfg": cfg,
                         "sampler_name": sampler, "scheduler": scheduler,
                         "denoise": 1.0}},
        "6": {"class_type": "VAEDecode",
              "inputs": {"samples": ["5", 0], "vae": ["1", 2]}},
        "7": {"class_type": "SaveImage",
              "inputs": {"images": ["6", 0],
                         "filename_prefix": "installer_asset"}},
    }


def _img2img_workflow(ckpt: str, prompt: str, negative: str,
                      input_image_name: str, *,
                      denoise: float = 0.45,
                      steps: int = 28, cfg: float = 6.5,
                      sampler: str = "dpmpp_2m_sde",
                      scheduler: str = "karras",
                      seed: int | None = None) -> dict:
    """img2img workflow seeded from an uploaded image — used for the
    loading-sequence frame chain. Lower denoise preserves the base
    composition while the prompt morph nudges the visual phase."""
    s = seed if seed is not None else int.from_bytes(os.urandom(4), "big")
    return {
        "1": {"class_type": "CheckpointLoaderSimple",
              "inputs": {"ckpt_name": ckpt}},
        "2": {"class_type": "CLIPTextEncode",
              "inputs": {"text": prompt, "clip": ["1", 1]}},
        "3": {"class_type": "CLIPTextEncode",
              "inputs": {"text": negative, "clip": ["1", 1]}},
        "4": {"class_type": "LoadImage",
              "inputs": {"image": input_image_name}},
        "5": {"class_type": "VAEEncode",
              "inputs": {"pixels": ["4", 0], "vae": ["1", 2]}},
        "6": {"class_type": "KSampler",
              "inputs": {"model": ["1", 0], "positive": ["2", 0],
                         "negative": ["3", 0], "latent_image": ["5", 0],
                         "seed": s, "steps": steps, "cfg": cfg,
                         "sampler_name": sampler, "scheduler": scheduler,
                         "denoise": denoise}},
        "7": {"class_type": "VAEDecode",
              "inputs": {"samples": ["6", 0], "vae": ["1", 2]}},
        "8": {"class_type": "SaveImage",
              "inputs": {"images": ["7", 0],
                         "filename_prefix": "installer_asset_chain"}},
    }


def upload_image(server: str, local_path: Path,
                 upload_name: str | None = None) -> str:
    """Upload a PNG to ComfyUI's input dir; returns the server-side filename."""
    import mimetypes
    if upload_name is None:
        upload_name = f"installer_chain_{uuid.uuid4().hex[:8]}.png"
    boundary = uuid.uuid4().hex
    ctype = mimetypes.guess_type(str(local_path))[0] or "image/png"
    with open(local_path, "rb") as f:
        data = f.read()
    body = (
        f"--{boundary}\r\n"
        f'Content-Disposition: form-data; name="image"; '
        f'filename="{upload_name}"\r\n'
        f"Content-Type: {ctype}\r\n\r\n"
    ).encode() + data + f"\r\n--{boundary}--\r\n".encode()
    req = urllib.request.Request(
        f"{server}/upload/image", data=body,
        headers={"Content-Type":
                 f"multipart/form-data; boundary={boundary}"},
        method="POST")
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read()).get("name", upload_name)


