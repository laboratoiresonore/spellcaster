def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--server", default=DEFAULT_SERVER,
                        help=f"ComfyUI server URL (default: {DEFAULT_SERVER})")
    parser.add_argument("--only", default="",
                        help="Comma-separated category filter "
                             "(feature,arch,background,hero,completion,error,loading)")
    parser.add_argument("--list", action="store_true",
                        help="Print the asset catalog and exit")
    parser.add_argument("--dry-run", action="store_true",
                        help="Resolve models + prompts, but skip generation")
    parser.add_argument("--overwrite", action="store_true",
                        help="Re-render even if output already exists")
    parser.add_argument("--seed", type=int, default=None,
                        help="Fixed seed for reproducible runs")
    args = parser.parse_args()

    if args.list:
        for a in ASSETS:
            print(f"  {a['category']:11s} {a['key']:28s} "
                  f"{a['size'][0]}×{a['size'][1]:<5d} -> {a['filename']}")
        print(f"\n  Total: {len(ASSETS)} assets")
        return 0

    server = args.server.rstrip("/")
    only = {c.strip() for c in args.only.split(",") if c.strip()}
    jobs = [a for a in ASSETS if not only or a["category"] in only]

    print(f"\n{'='*64}")
    print(f"  Spellcaster Installer Asset Generator")
    print(f"  Server:  {server}")
    print(f"  Assets:  {len(jobs)}{f' ({args.only})' if only else ''}")
    print(f"  Output:  {OUTPUT_DIR.relative_to(REPO_ROOT)}")
    print(f"{'='*64}\n")

    # Probe server for available models
    print("Probing checkpoint inventory…")
    available = fetch_checkpoints(server)
    if not available:
        print("  No checkpoints reachable. Aborting.")
        return 2
    print(f"  {len(available)} checkpoints available")

    # Resolve a concrete ckpt for each model_class actually used
    used_classes = sorted({j["model_class"] for j in jobs})
    resolved: dict[str, str] = {}
    for cls in used_classes:
        m = pick_model(cls, available)
        if not m:
            print(f"  WARN: no checkpoint matched class '{cls}'")
            continue
        resolved[cls] = m
        print(f"  {cls:18s} -> {m}")

    if args.dry_run:
        print("\n[dry-run] not generating. Re-run without --dry-run to render.")
        return 0

    print(f"\nRendering {len(jobs)} assets…\n")
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    # Group chain-sequence specs so a sequence's frames render in order
    # using the same RNG seed (so the chain's morph is coherent).
    seq_seeds: dict[str, int] = {}

    ok = 0
    skip = 0
    fail = 0
    t0 = time.time()
    for i, spec in enumerate(jobs, 1):
        dest = OUTPUT_DIR / spec["filename"]
        if dest.exists() and not args.overwrite:
            print(f"  [{i:2d}/{len(jobs)}] SKIP (exists) {spec['filename']}")
            skip += 1
            continue
        ckpt = resolved.get(spec["model_class"])
        if not ckpt:
            print(f"  [{i:2d}/{len(jobs)}] FAIL no model for "
                  f"{spec['model_class']}: {spec['filename']}")
            fail += 1
            continue

        w, h = spec["size"]
        steps = spec.get("steps", DEFAULT_STEPS)
        cfg = spec.get("cfg", DEFAULT_CFG)
        sampler = spec.get("sampler", DEFAULT_SAMPLER)
        scheduler = spec.get("scheduler", DEFAULT_SCHEDULER)

        # Sequence handling: chain_idx 0 = txt2img base, 1.. = img2img refs
        chain_seq = spec.get("chain_seq")
        chain_idx = spec.get("chain_idx", 0)

        # Reuse one seed per sequence so all frames build on the same look
        if chain_seq:
            if chain_seq not in seq_seeds:
                seq_seeds[chain_seq] = (args.seed if args.seed is not None
                                        else int.from_bytes(os.urandom(4),
                                                            "big"))
            seed = seq_seeds[chain_seq]
        else:
            seed = args.seed

        if chain_seq and chain_idx > 0:
            # img2img frame — needs the previous frame uploaded
            prev_filename = spec["filename"].rsplit("_", 1)[0] \
                            + f"_{chain_idx - 1:02d}.png"
            prev_path = OUTPUT_DIR / prev_filename
            if not prev_path.exists():
                print(f"  [{i:2d}/{len(jobs)}] FAIL chain prev missing: "
                      f"{prev_filename}")
                fail += 1
                continue
            try:
                uploaded = upload_image(server, prev_path)
            except Exception as e:  # noqa: BLE001
                print(f"  [{i:2d}/{len(jobs)}] FAIL upload: {e}")
                fail += 1
                continue
            wf = _img2img_workflow(
                ckpt, spec["prompt"], spec["negative"],
                input_image_name=uploaded,
                denoise=spec.get("chain_denoise", 0.45),
                steps=steps, cfg=cfg, sampler=sampler, scheduler=scheduler,
                seed=seed)
            label = f"img2img f{chain_idx} ({w}×{h})"
        else:
            wf = _txt2img_workflow(
                ckpt, spec["prompt"], spec["negative"], w, h,
                steps=steps, cfg=cfg, sampler=sampler, scheduler=scheduler,
                seed=seed)
            label = f"({w}×{h}, {steps}st)"

        print(f"  [{i:2d}/{len(jobs)}] {spec['filename']} {label} … ",
              end="", flush=True)
        pid = queue_prompt(server, wf)
        if not pid:
            print("FAIL queue")
            fail += 1
            continue
        blob = wait_and_fetch(server, pid)
        if not blob:
            print("FAIL no output")
            fail += 1
            continue
        downscale_save(blob, dest, spec["final_size"])
        size_kb = dest.stat().st_size / 1024
        print(f"OK ({size_kb:.0f} KB)")
        ok += 1

    elapsed = time.time() - t0
    print(f"\n{'='*64}")
    print(f"  Done in {elapsed:.0f}s — {ok} OK, {skip} skipped, {fail} failed")
    print(f"  Output dir: {OUTPUT_DIR}")
    print(f"{'='*64}\n")
    return 0 if fail == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
