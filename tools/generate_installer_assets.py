# Substring matching is order-sensitive: we walk hints in priority and return
# the first match whose path also passes class_filter(). Filters keep us from
# accidentally choosing an SD 1.5 ckpt when we asked for SDXL.
_MODEL_CLASS_HINTS: dict[str, list[str]] = {
    "sdxl_realistic": [
        "juggernautxl", "realvisxl", "rundiffusion", "epicrealism",
        "sdxl_real", "realistic",
    ],
    "sdxl_clean": [
        "moderndisney", "modern_disney", "modernpixar",
        "noobai", "ilustreal", "pixar", "disney", "anime", "stylized",
    ],
}

# Path-segment exclusion patterns per class. We disqualify candidates whose
# normalized path contains any of these tokens — eg. /SD-1.5/, /sd15/.
_CLASS_EXCLUDE: dict[str, list[str]] = {
    "sdxl_realistic": ["sd-1.5/", "sd15/", "sd1.5/", "/flux/", "/wan/", "/ltx/", "/chroma/"],
    "sdxl_clean":     ["sd-1.5/", "sd15/", "sd1.5/", "/flux/", "/wan/", "/ltx/", "/chroma/"],
}

# Class-specific positive REQUIRE: every candidate path MUST contain at least
# one of these substrings to be considered. Belt-and-suspenders against
# matching the wrong arch.
_CLASS_REQUIRE: dict[str, list[str]] = {
    "sdxl_realistic": ["sdxl/", "sdxl\\", "_xl_", "xl_v", "xl-v"],
    "sdxl_clean":     ["sdxl/", "sdxl\\", "_xl_", "xl_v", "xl-v"],
}


def fetch_checkpoints(server: str) -> list[str]:
    """Probe /object_info/CheckpointLoaderSimple for installed ckpt names."""
    try:
        with urllib.request.urlopen(
                f"{server}/object_info/CheckpointLoaderSimple", timeout=15) as r:
            data = json.loads(r.read())
        items = (data.get("CheckpointLoaderSimple", {}).get("input", {})
                 .get("required", {}).get("ckpt_name", [None])[0])
        return list(items) if isinstance(items, list) else []
    except Exception as exc:  # noqa: BLE001
        print(f"  ERROR: could not fetch checkpoints: {exc}")
        return []


def _passes_class_filter(class_key: str, ckpt: str) -> bool:
    """Apply per-class require/exclude rules — guards against arch mismatch."""
    norm = ckpt.replace("\\", "/").lower()
    for token in _CLASS_EXCLUDE.get(class_key, []):
        if token in norm:
            return False
    require = _CLASS_REQUIRE.get(class_key, [])
    if require and not any(tok in norm for tok in require):
        return False
    return True


def pick_model(class_key: str, available: list[str]) -> str | None:
    """Choose the first checkpoint matching the class's hint + filter rules.

    Falls back to the first checkpoint that PASSES the class filter even if
    no positive hint matched (covers users with non-canonically-named SDXL
    models). Returns None if nothing in inventory satisfies the class.
    """
    eligible = [(c, c.lower()) for c in available
                if _passes_class_filter(class_key, c)]
    hints = _MODEL_CLASS_HINTS.get(class_key, [])
    for hint in hints:
        for orig, low in eligible:
            if hint in low:
                return orig
    # No positive hint matched, but at least one model passes the class
    # filter — use it. Better than crashing or picking the wrong arch.
    return eligible[0][0] if eligible else None


