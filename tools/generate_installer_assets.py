def queue_prompt(server: str, workflow: dict) -> str | None:
    payload = json.dumps({"prompt": workflow,
                          "client_id": str(uuid.uuid4())}).encode()
    req = urllib.request.Request(
        f"{server}/prompt", data=payload,
        headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return json.loads(r.read()).get("prompt_id")
    except urllib.error.HTTPError as e:
        body = e.read().decode(errors="replace")
        print(f"    ERROR {e.code}: {body[:300]}")
        return None
    except Exception as e:  # noqa: BLE001
        print(f"    ERROR: {e}")
        return None


def wait_and_fetch(server: str, prompt_id: str,
                   timeout: int = 600) -> bytes | None:
    start = time.time()
    while time.time() - start < timeout:
        try:
            with urllib.request.urlopen(
                    f"{server}/history/{prompt_id}", timeout=10) as r:
                hist = json.loads(r.read())
            if prompt_id not in hist:
                time.sleep(2); continue
            outs = hist[prompt_id].get("outputs", {})
            for node_out in outs.values():
                images = node_out.get("images") or []
                if images:
                    img = images[0]
                    fn = img["filename"]
                    sub = img.get("subfolder", "")
                    typ = img.get("type", "output")
                    url = (f"{server}/view?filename={fn}"
                           f"&subfolder={sub}&type={typ}")
                    with urllib.request.urlopen(url, timeout=60) as r:
                        return r.read()
            time.sleep(2)
        except Exception:
            time.sleep(2)
    return None


def downscale_save(blob: bytes, dest: Path,
                   final_size: tuple[int, int]) -> None:
    """Decode, resize with Lanczos, save PNG."""
    try:
        from PIL import Image
        import io
        img = Image.open(io.BytesIO(blob))
        if img.size != final_size:
            img = img.resize(final_size, Image.LANCZOS)
        dest.parent.mkdir(parents=True, exist_ok=True)
        img.save(dest, "PNG", optimize=True)
    except ImportError:
        # No Pillow — write the raw blob and let downstream resize
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(blob)


